def main() -> None:
    sizes = json.load(open("scratch/gt_grid/sizes.json", encoding="utf-8"))
    out = {}
    for iid, info in sizes.items():
        w = info["width"]
        h = info["height"]
        pts = NORM_LABELS[iid]
        corners_px = [
            [round(x / 1000.0 * (w - 1), 1), round(y / 1000.0 * (h - 1), 1)]
            for x, y in pts
        ]
        out[iid] = {
            "corners": corners_px,
            "width": w,
            "height": h,
            "split": info["split"],
            "condition": info["condition"],
        }

    Path("data/labels.json").write_text(json.dumps(out, indent=2), encoding="utf-8")
    print(f"Wrote data/labels.json with {len(out)} entries.")


if __name__ == "__main__":
    main()
